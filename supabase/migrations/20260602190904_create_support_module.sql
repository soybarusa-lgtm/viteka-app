  pharmacy_id uuid references public.pharmacies(id),
  support_company_id uuid references public.support_companies(id) on delete set null,
  requester_contact_id uuid references public.support_contacts(id) on delete set null,
  requester_profile_id uuid references public.profiles(id) on delete set null,
  external_freshdesk_id text,
