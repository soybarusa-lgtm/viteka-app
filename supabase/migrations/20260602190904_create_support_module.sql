create or replace function public.support_get_my_pharmacy_id()
returns uuid language sql stable
as $$ select pharmacy_id from public.profiles where id = auth.uid() $$;

create or replace function public.support_is_internal()
returns boolean language sql stable
as $$ select coalesce(public.get_my_role() in ('owner', 'superadmin', 'admin', 'technician', 'tecnico', 'commercial', 'comercial'), false) $$;

create or replace function public.support_can_access_ticket(ticket_uuid uuid)
returns boolean language sql stable
as $$
  select exists (
    select 1 from public.support_tickets ticket
    where ticket.id = ticket_uuid
      and ticket.company_id = public.get_my_company_id()
      and (
        public.get_my_role() in ('owner', 'superadmin', 'admin', 'commercial', 'comercial')
        or (public.get_my_role() in ('technician', 'tecnico') and ticket.assigned_agent_id = auth.uid())
        or ticket.pharmacy_id = public.support_get_my_pharmacy_id()
      )
  )
$$;

create or replace function public.support_touch_updated_at()
returns trigger language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end
$$;

